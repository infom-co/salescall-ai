MODELS = {"3.8 Flash": 2, "3.7 Flash": 2, "3.6 Flash": 2, "3 Flash": 2, "3.5 Flash Lite": 3}  # 鍵 ⇒ 回数


def judge(ok: tuple, unit: str) -> str:
    if not unit:
        return "正しい" if not ok else "補わない"
    return "正しい" if any(same_unit(unit, o) for o in ok) else "誤り"


def tally(units: list[str]) -> dict:
    out = {"正しい": 0, "補わない": 0, "誤り": 0, "誤りの例": [], "補わない例": []}
    for (b, q, ok, _), u in zip(QUESTIONS, units):
        j = judge(ok, u)
        out[j] += 1
        if j == "誤り":
            out["誤りの例"].append(f"{q} ⇒ 「{u}」（正解：{'・'.join(ok) or '空'}）")
        elif j == "補わない":
            out["補わない例"].append(q)
    return out


def combine(rule: list[str], runs: dict[str, list[str]]) -> dict:
    """組み合わせ方を比べる（units.decide の形は、この数で決めた）。"""
    out = {"決まりだけ": tally(rule)}
    for k, v in runs.items():
        out[f"決まり→{k}だけ"] = tally([r or m for r, m in zip(rule, v)])  # 決まりで決まれば決まり、無ければそのモデル
    for a, b in itertools.combinations(runs, 2):  # 決まり→2つのモデルが合うときだけ（units.decide そのもの）
        out[f"決まり→{a}×{b}"] = tally([decide(q, [x, y]) for (_, q, _, _), x, y in zip(QUESTIONS, runs[a], runs[b])])
    return out


def rescore(path: str) -> dict:
    """保存した結果のモデルの答え（raw_unit）を、いまの units（そろえ方・合わせ方）と正解で数え直す（問い合わせはしない）。"""
    d = json.loads(open(path, encoding="utf-8").read())
    runs = {k: [clean_unit(r["raw_unit"]) for r in v["rows"]] for k, v in d["raw"].items() if "rows" in v}
    rule = [by_rule(q) for _, q, _, _ in QUESTIONS]
    return {"rescored_from": path, "questions": [{"business": b, "question": q, "ok": list(ok), "form": f, "rule": r}
                                                 for (b, q, ok, f), r in zip(QUESTIONS, rule)],
            "model_ids": d.get("model_ids"), "raw": d["raw"], "compare": combine(rule, runs)}


def run(args) -> dict:
    rule = [by_rule(q) for _, q, _, _ in QUESTIONS]
    out = {"questions": [{"business": b, "question": q, "ok": list(ok), "form": f, "rule": r}
                         for (b, q, ok, f), r in zip(QUESTIONS, rule)], "rule": tally(rule)}
    say("決まりだけ：", json.dumps({k: v for k, v in out["rule"].items() if not k.endswith("例")}, ensure_ascii=False))
    if args.dry_run:
        return out
    client = make_client(pick_key(args))
    ids, flash_names = find_models(client)
    out["model_ids"], out["flash_display_names"] = ids, flash_names
    say("モデルID：", ids)
    plan = [(k, rep) for k, n in MODELS.items() if k in ids and (not args.model_key or k in args.model_key) for rep in range(n)]
    asked = [(B[b], q) for b, q, _, _ in QUESTIONS]
    raw, runs = {}, {}
    for k, rep in sorted(plan, key=lambda x: x[1]):  # 1回目を全部のモデルで回してから2回目へ（同じモデルへの問い合わせの間を空ける）
        name = f"{k}#{rep}"
        try:
            got, retries = call_with_retry(lambda: by_model(client, ids[k], asked))
            raw[name] = {"rows": got, "retries": retries}
            runs[name] = [g["unit"] for g in got]
            t = tally(runs[name])
            say(name, f"正しい {t['正しい']}／補わない {t['補わない']}／誤り {t['誤り']}", t["誤りの例"])
        except Exception as exc:
            raw[name] = {"error": describe_error(exc)}
            say(name, "誤りで止まりました：", raw[name]["error"].get("message", "")[:200])
            if "429" in str(raw[name]["error"].get("code", "")) or "RESOURCE_EXHAUSTED" in raw[name]["error"].get("message", ""):
                say("⛔ 上限に当たったので、ここで止めます（やり直さない）")
                break
        save_partial("G-41", {"raw": raw})
        time.sleep(args.pause)
    out["raw"] = raw
    out["compare"] = combine(rule, runs)
    show(out["compare"])
    return out


def show(compare: dict) -> None:
    for k, v in compare.items():
        say(k, f"正しい {v['正しい']}／補わない {v['補わない']}／誤り {v['誤り']}", v["誤りの例"] or "")


def main() -> None:
    require_python()
    p = base_parser(__doc__)
    p.add_argument("--pause", type=float, default=15.0)
    p.add_argument("--model-key", choices=list(MODELS), action="append")
    p.add_argument("--rescore", help="保存した結果を、いまの units と正解で数え直す（問い合わせはしない）")
    args = p.parse_args()
    if args.rescore:
        out = rescore(args.rescore)
        show(out["compare"])
        save_result("G-41", out)
        return
    save_result("G-41", run(args))
    drop_partial("G-41")


if __name__ == "__main__":
    main()

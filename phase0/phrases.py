"""AIが言う「決まった言い方」の唯一の場所（DESIGN.md 6-11 の聞き返し・復唱・念のための確認）。

指示文（instruction.system_rules）と、流れの制御の返事（flowctl）の両方が、ここを読む。言い方を書き写さない。
- ASK_BACK：その場で聞き取れない・曖昧な必須項目を、1回だけ聞き返す
- RECHECK：「-」の項目を、会話の最後か切りの良いときに、もう1回だけ聞く前に言う
- confirm：聞き取った値を言い直して（復唱して）、合っているかを聞く
  ⛔ 2026-10-13 G-16 の2回目：復唱の言い方が決まっていなかったため、AIが「16日の午後2時で伺いました」と問いかけでない形で言い、
     相手の「はい、そうです」を確認の返事として報告しなかった（3本中3本）⇒ 問いかけの形に決めた
  ✅ 2026-10-13 ユーザー：基本は「（値）で、よろしいでしょうか。」。ただし同じ言い方の連発は機械っぽいので、場面ごとに複数用意する
     （聞き取れなかったあとは「（値）で、よろしかったでしょうか？」「（値）と、おっしゃいましたでしょうか？」、確認の場面では
     「（値）で、大丈夫でしょうか？」）。⇒ 場面（CONFIRM の鍵）を流れの制御が決め、同じ場面の中では順番に回す（n）。
     ⚠️「大丈夫でしょうか」を「ふつう」に入れたのは、こちらの解釈（ユーザーの「確認的な場面」の意味は確かめ中）
- BUSY_ASK：相手が「忙しい」と言ったとき、業務設定で「引き止める」を選んだ場合に、1回だけ言う一言の既定の文
- LEAD_IN：プログラムの返事を受けてから話す文の頭に置く、受けの言葉（DESIGN.md 6-11 の案。⏳ ユーザーの承認前）
  ⛔ 2026-10-13 G-16・G-24：AIがプログラムの返事を受けてから話すと、声の頭の1〜3音が崩れる（言い直しの「15日」が「5日」に）。
  ✅ G-25：言い直しの頭に「ありがとうございます。」を置くと、言い直しの頭の崩れが 42%→0%。⇒ 値・質問の言葉を文の頭に置かない。
     同じ言葉の連発を避けるため、種類ごとに順番に回す
"""
from __future__ import annotations

ASK_BACK = "聞き取りにくかったので、もう一度、おっしゃっていただいてよろしいでしょうか。"
RECHECK = "念のため確認させてください。"
CONFIRM = {
    "ふつう": ("{v}で、よろしいでしょうか。", "{v}で、大丈夫でしょうか。"),                       # その場ではっきり聞けた値
    "聞き取りにくかったあと": ("{v}と、おっしゃいましたでしょうか。", "{v}で、よろしかったでしょうか。"),  # 聞き返し・念のための確認・訂正のあと
}
BUSY_ASK = "お忙しいところ申し訳ございません。少しだけ、お時間をいただけますでしょうか。"


def confirm(value: str, situation: str = "ふつう", n: int = 0) -> str:
    """言い直しの言い方。situation は CONFIRM の鍵、n はその場面で何回目か（順番に回す）。"""
    forms = CONFIRM[situation]
    return forms[n % len(forms)].format(v=value)

LEAD_IN = {
    "言い直し": ("ありがとうございます。", "かしこまりました。", "承知いたしました。"),
    "次の質問": ("それでは、", "続きまして、", "では、"),
}


def lead_in(kind: str, n: int) -> str:
    """受けの言葉。kind は LEAD_IN の鍵、n はその種類で何回目か（順番に回す）。"""
    forms = LEAD_IN[kind]
    return forms[n % len(forms)]

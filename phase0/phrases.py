from __future__ import annotations

ASK_BACK = "聞き取りにくかったので、もう一度、おっしゃっていただいてよろしいでしょうか。"
RECHECK = "念のため確認させてください。"
CONFIRM = {
    "ふつう": ("{v}で、よろしいでしょうか。", "{v}で、大丈夫でしょうか。"),                       # その場ではっきり聞けた値
    "聞き取りにくかったあと": ("{v}と、おっしゃいましたでしょうか。", "{v}で、よろしかったでしょうか。"),  # 聞き返し・念のための確認・訂正のあと
}
BUSY_ASK = "お忙しいところ申し訳ございません。少しだけ、お時間をいただけますでしょうか。"
CLOSE_DECLINED = "お忙しいところ、申し訳ございませんでした。それでは、失礼いたします。"


def confirm(value: str, situation: str = "ふつう", n: int = 0) -> str:
    """言い直しの言い方。situation は CONFIRM の鍵、n はその場面で何回目か（順番に回す）。"""
    forms = CONFIRM[situation]
    return forms[n % len(forms)].format(v=value)

APOLOGY = ("失礼いたしました。", "申し訳ございません。")
ACKNOWLEDGE = ("はい", "承知しました", "ありがとうございます", "そうですね", "恐れ入ります", "おっしゃる通りです", "なるほどですね", "そう思います")
LEAD_IN = {
    "言い直し": ("ありがとうございます。", "かしこまりました。", "承知いたしました。"),
    # 受けの言葉が先の形（ack_first）では、AIがもう受けの言葉を言っているので、言い直しの頭はつなぎの言葉にする（重ねない）。
    # ⏳ 言い方はユーザーの承認前（G-33 で聞いていただく）
    "言い直しのつなぎ": ("確認いたします。", "復唱いたします。"),
    "次の質問": ("それでは、", "続きまして、", "では、"),
}


def lead_in(kind: str, n: int) -> str:
    """受けの言葉。kind は LEAD_IN の鍵、n はその種類で何回目か（順番に回す）。"""
    forms = LEAD_IN[kind]
    return forms[n % len(forms)]

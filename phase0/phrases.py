def joiner(value: str) -> str:
    """値と「、よろしいでしょうか」をつなぐ言葉。値の終わりが名詞（「時」「人」「末」など）なら「で」、それ以外（「いつでも」
    「なるべく早く」「いつでも大丈夫」）なら「ということで」（「いつでも大丈夫で、よろしいでしょうか」は不自然。2026-10-14：
    ユーザー確定「『いつでも』『なるべく早く』は『即』＝よい答え」で、日時の質問の答えとして受け付けるようにしたため）。"""
    from jtext import words
    ws = list(words(value))
    pos = getattr(ws[-1].feature, "pos1", "") if ws else ""
    return "で" if pos in ("名詞", "接尾辞", "補助記号", "記号") else "ということで"


def client_does_words(does: str = "") -> str:
    """事実を伺う質問の確かめ「…ということで（ここ）大丈夫でしょうか？」の言葉を作る唯一の場所：業務設定の依頼者がすること（登録・手配など）があれば
    「（それ）させていただいて」、無ければ「承っておいて」（NOTED_DOES）。"""
    return f"{does}させていただいて" if does else NOTED_DOES


def confirm(value: str, situation: str = "ふつう", n: int = 0, meaning: bool = False, does: str = "") -> str:
    """言い直しの言い方。situation は CONFIRM の鍵、n はその場面で何回目か（順番に回す）。
    meaning：選択肢の答えの意味を言い直すとき（「ご予約はお済みということでよろしいでしょうか？」。value は flowctl.choice_words）。
    言葉を聞き返す形（「（値）とおっしゃいましたでしょうか？」）は、意味の言い直しには合わないので使わない。
    does：業務設定の依頼者がすること（空なら無い。事実を伺う質問の、言い切っていない答えのあとの形だけが使う＝client_does_words）。"""
    forms = [f for f in CONFIRM[situation] if not meaning or "とおっしゃいました" not in f]
    # 言い直す言葉と語尾で、同じ言葉を2回言わない（「お送りして大丈夫だということで大丈夫でしょうか」・「よろしいということでよろしい…」）。
    # ✅ 2026-10-18 ユーザー：「語尾に『よろしい』が2回は違和感」
    forms = [f for f in forms if not any(w in value and w in f for w in ("よろし", "大丈夫"))] or forms
    return forms[n % len(forms)].format(v=value, de=joiner(value), does=client_does_words(does))


def restate_words(words: str, said: str | None = None) -> str:
    """選択肢の意味の言葉に「よろしい」が入っていれば（申し出の質問の「パンフレットをお送りしてよろしいということ」）、お客様が言った言葉
    （「大丈夫です」⇒「大丈夫だ」・「結構です」⇒「結構だ」・「いいです」⇒「いい」）に替える。お客様の言葉に無ければ「大丈夫だ」。
    ✅ 2026-10-18 ユーザー：「『はい、念のためパンフレットをお送りして大丈夫だということでよろしかったでしょうか？』語尾に『よろしい』が2回は
       違和感。相手が言ったことを聞き返した方が確か」"""
    if "よろしい" not in words:
        return words
    from flowctl import ambiguous_word

    w = ambiguous_word(said)
    return words.replace("よろしい", "いい" if w == "いい" else f"{w or '大丈夫'}だ")


def by_model(client, model: str, questions: list[tuple[str, tuple]], kind: str = "meaning") -> list[dict]:
    """questions＝[(質問の文, 選択肢の並び)]。1回の問い合わせでまとめて答えさせ、質問ごとに {選択肢: 言葉}（そろえたもの）を返す。kind＝言葉の種類（PROMPTS）。
    送り先は部品の作りで決まる（Gemini・Anthropic とも同じ文・同じ読み取り＝askitems.ask）。"""
    from askitems import ask

    return _read_items(ask(client, model, PROMPTS[kind] + _body(questions), FIELDS, tool=TOOL), questions)


def _body(questions: list[tuple]) -> str:
    """問い合わせの本文の質問の一覧（唯一の場所＝Gemini も Anthropic も）：「番号：質問の文／選択肢・選択肢」。質問に意味の言葉（3つ目＝{選択肢: 言葉}）が
    あれば、選択肢ごとに「選択肢（意味の言葉）」と添える（打ち消しの問いの「はい」を、名前ではなく意味で読ませる＝AWAY_PROMPT）。"""
    def opts(c, m):
        return "・".join(f"{x}（{m[x]}）" if m and m.get(x) else x for x in c)
    return "\n".join(f"{n}：{q[0]}／{opts(q[1], q[2] if len(q) > 2 else None)}" for n, q in enumerate(questions, 1))


def _read_items(items: list, questions: list[tuple[str, tuple]]) -> list[dict]:
    """答えの items を、質問ごとの {選択肢: 言葉} にそろえる（読み取りの唯一の場所＝Gemini も Anthropic も）。"""
    out = [{} for _ in questions]
    for x in items or []:
        n = x.get("no") if isinstance(x, dict) else None
        if isinstance(n, int) and 1 <= n <= len(questions) and clean(x.get("choice")) in questions[n - 1][1]:
            out[n - 1][clean(x.get("choice"))] = clean(x.get("words"))
    return out



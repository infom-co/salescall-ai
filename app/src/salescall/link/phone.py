"""PC の電話の部品（電話接続の担当。まだ振っていない）の形（DESIGN.md 5-5）。持ち主 CL-2（形だけ）。

PC の部品が、回線（スマホ1台）ごとに1つ作る（設定の `モジュール:名前` から。回線の ID を受け取る）。サーバーの発信の出口
（core/dial_exit.py）が「かける」と決めたときだけ、PC の部品がサーバーの頼みを受けて `start_call` を呼ぶ（I-1）。
"""

from __future__ import annotations

from typing import Any, Callable, Protocol


class CallNotPlaced(Exception):
    """電話の部品が、かけようとして、かけられなかった（アプリが番号を受け付けなかった・アプリの誤りなど＝お客様の電話は鳴っていない
    と確かに言える失敗）。**番号のせいか回線のせいかは、ここでは決めない**：試行は「発信に失敗」になり、同じ回線の前後の電話の証拠で
    決まる（データベースの1か所 salescall.unrung_blame＝0129。同じ回線がそのあとほかの番号を鳴らせたら番号のせい、鳴った電話を
    挟まずに違う番号も続けて鳴らなければ回線のせい）。⛔ 0129：前は「番号のせい」（NumberRejected）と「回線のせい・分からない」を
    アプリの言い分で分け、どの番号も受け付けない回線（アプリの設定の誤り）では行がすべて終わり、1つの番号だけが続けてかけられない
    ときは回線が止まり続けた（見直し18a の問題2・3）。"""


class CallWithheld(Exception):
    """かけようとしなかった（PC の上で緊急停止が押されている・PC の部品がつながっていない・前の頼みを待つうちに答えの期限を過ぎた）。
    番号も回線も試していないので、どの数にも入れない（試行は取り消し）。"""


class Phone(Protocol):
    def in_call(self) -> bool:
        """スマホが、いま通話の途中か（呼び出し中を含む）。分からなければ True（かけない側）。"""

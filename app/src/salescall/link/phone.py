"""PC の電話の部品（電話接続の担当。まだ振っていない）の形（DESIGN.md 5-5）。持ち主 CL-2（形だけ）。

PC の部品が、回線（スマホ1台）ごとに1つ作る（設定の `モジュール:名前` から。回線の ID を受け取る）。サーバーの発信の出口
（core/dial_exit.py）が「かける」と決めたときだけ、PC の部品がサーバーの頼みを受けて `start_call` を呼ぶ（I-1）。
"""

from __future__ import annotations

from typing import Any, Callable, Protocol


class CallNotPlaced(Exception):
    """電話の部品が、電話をかけていないと確かに言える失敗。**番号のせいか回線のせいかの分け方は、この形と下の NumberRejected の
    1か所**（⛔ 見直し17c：前は1つの形で、番号のせい（アプリが番号を受け付けなかった）も回線の異常として数え、同時に番号の歯止めでも
    数えていた＝1回の失敗を2か所で数えた）。
    - この形のまま上げる＝回線のせい、または、どちらのせいか分からない：回線の異常としてだけ数える（続けば回線を止めて知らせる）。
      試行は取り消す（番号の歯止めには数えない）。分からないときを回線の側に倒すのは、番号の側に倒すと、回線が壊れているあいだに
      かけた番号がつぎつぎ「使えない番号」になり、お客様を失うから（回線の停止は管理者と契約者に知らされ、解けば戻る）。
    - 番号のせいと確かに言えるときだけ NumberRejected を上げる。"""


class NumberRejected(CallNotPlaced):
    """アプリ（電話の部品）が、その番号を受け付けなかった（番号の形が違う・その番号にはかけられない、など番号のせいと確かに言える）。
    番号の歯止め（同じ番号で続けて受け付けられなければ、決まった順でかけ直し、4回でその番号へはかけない＝core/next_action）でだけ
    数え、回線の異常には数えない。回線は休ませず、次の行へ進む。"""


class CallWithheld(CallNotPlaced):
    """かけなかった（PC の上で緊急停止が押されている・PC の部品がつながっていない）。回線の異常ではないので、数えない。"""



    def start_call(self, phone_e164: str, voice_type: str | None = None) -> None:
        """かける。voice_type＝この通話で話す声の型（門が決めたもの）。通話の途中でおわびの録音を流すとき
        （`play_apology_and_hang_up`）は、この声の型の録音を流す（AI の声と違う声にしない。2026-10-22 の見直し14）。"""
        ...

    def hang_up(self) -> None: ...

    def test_ring(self, phone_e164: str) -> bool | None:
        """テスト番号（契約者が用意した、お客様ではない電話）へかけ、**この回線から電話網へ発信できたか**を答える（0141。2026-10-25 夜
        管理者：「テスト番号が話し中・電源オフ・圏外だと分かるのなら、回線の問題じゃないんじゃないの？」）。
        - True＝回線から発信できた：呼び出しの音が出た（お客様の電話でいう「鳴った」。相手が出る前に切る）・話し中の音が返った・
          電源が切れている／圏外のお知らせの声が返った（どれも、電話網がこの回線の発信を受け付けた証拠＝回線は元気）。
        - False＝回線から発信できない：アプリが発信できない・呼び出しの音もお知らせの声も無いまま終わった（回線のせい）。
        - None＝見分けられない（呼び出しの音・話し中の音・お知らせの声のどれかが返ったか分からない）。回線のせいにも番号のせいにも
          しない（サーバーは、契約者と管理者にすぐ1回知らせ、電話をつなぐ部品の担当へ修正依頼を出す）。話している途中なら、PC の部品が
          試さない（サーバーへは withheld＝記録しない。0143）。
        ⛔ 0136〜0140：話し中・電源オフ・圏外を None（分からない）としていた。
        答えは `protocol.ANSWER_BY` 秒のうちに（呼び出しの音を待つのは、それより短く）。サーバーは、鳴ったテストを「その回線で電話が
        鳴った」証拠にし、鳴らなかったテストを回線のせいの証拠にする（core/ring_test。2026-10-24 ユーザー決定）。"""
        ...

    def play_apology_and_hang_up(self) -> None:
        """あらかじめ持っている、おわびの録音を流して切る（お客様を無言で放置しない）。サーバーとのつながりが通話の途中で切れたとき・
        サーバーの側の誤りで頼まれたとき・その電話そのものに甚大な問題があるとき（2026-10-24 ユーザー決定。こちらのプログラムが3秒
        固まったときも）。通話中でなければ、何もしない。録音は、いまの通話の声の型（`start_call` で受け取った）のもの。
        **流し方（2026-10-22 ユーザー決定）**：(1) 録音「恐れ入ります。こちらの通信に不具合が起きたようですので、改めてお電話させて
        いただいてもよろしいでしょうか？」を流す (2) お客様の返事（『はい』）を待つ（AI はいないので中身は聞き分けない。お客様が話し
        終わるか、決まった秒数で次へ）(3) 録音「大変申し訳ございません。それではいったんお電話を失礼いたします。」を流す (4) 切る。
        どちらの録音もシステムの録音（どの業務でも同じ。声の型ごとに CL-1 が作る）：(1) は契約者の単位の録音の部分 `line_trouble_ask`、
        (3) は `line_trouble_bye`（名前の正本は CL-1 の phrases.RECORDED。CL-1 の連絡帳 4-37 の (b)。話してよい声は、契約者の組に
        これがそろっている声だけ＝core/recordings.CONTRACTOR_PARTS）。かけ直しは、サーバーが途中で切れた通話として
        お詫びから始める（core/next_action）。流し終えて切るまでを `protocol.APOLOGY_WAIT` 秒のうちに（サーバーは、それまで答えを
        待つ。返事を待つ「決まった秒数」も、その中に収める）。"""
        ...


# お客様の番号へかけて、電話網から返ったお知らせの声の種類（名前の正本はここ。2026-10-30。0151）：power_off＝電源が切れている／
# out_of_range＝電波の届かない所にある／not_in_use＝この番号は現在使われていない。見分けられなければ None。試行をどう終えるか
# （こちらの回線は元気か・番号のせいか）は、サーバーの1か所（core/attempts.end_by_notice）が決める（電話の部品は決めない）。
NOTICES: tuple[str, ...] = ("power_off", "out_of_range", "not_in_use")


class CallNotPlaced(Exception):
    """電話の部品が、かけようとして、かけられなかった（アプリが番号を受け付けなかった・アプリの誤りなど＝お客様の電話は鳴っていない
    と確かに言える失敗）。**番号のせいか回線のせいかは、ここでは決めない**：試行は「発信に失敗」になり、同じ回線の前後の電話の証拠で
    決まる（状態の表の試行のせいの欄＝DESIGN.md 17章。同じ回線がそのあとお客様の電話を鳴らせた・テスト番号が鳴ったら番号のせい、
    テスト番号が鳴らなければ回線のせい）。⛔ 0129：前は「番号のせい」（NumberRejected）と「回線のせい・分からない」を
    アプリの言い分で分け、どの番号も受け付けない回線（アプリの設定の誤り）では行がすべて終わり、1つの番号だけが続けてかけられない
    ときは回線が止まり続けた（見直し18a の問題2・3）。"""


class CallWithheld(Exception):
    """かけようとしなかった（PC の上で緊急停止が押されている・PC の部品がつながっていない・前の頼みを待つうちに答えの期限を過ぎた）。
    番号も回線も試していないので、どの数にも入れない（試行は取り消し）。"""



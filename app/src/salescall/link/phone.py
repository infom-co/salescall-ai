"""PC の電話の部品（電話接続の担当。まだ振っていない）の形（DESIGN.md 5-5）。持ち主 CL-2（形だけ）。

PC の部品が、回線（スマホ1台）ごとに1つ作る（設定の `モジュール:名前` から。回線の ID を受け取る）。サーバーの発信の出口
（core/dial_exit.py）が「かける」と決めたときだけ、PC の部品がサーバーの頼みを受けて `start_call` を呼ぶ（I-1）。
"""

from __future__ import annotations

from typing import Any, Callable, Protocol


class CallNotPlaced(Exception):
    """電話の部品が、かけようとして、かけられなかった（アプリが番号を受け付けなかった・アプリの誤りなど＝お客様の電話は鳴っていない
    と確かに言える失敗）。**番号のせいか回線のせいかは、ここでは決めない**：試行は「発信に失敗」になり、同じ回線の前後の電話の証拠で
    決まる（データベースの1か所 salescall.unrung_blame＝0129。同じ回線がそのあとほかの番号を鳴らせたら番号のせい、鳴った電話を
    挟まずに違う番号も続けて鳴らなければ回線のせい）。⛔ 0129：前は「番号のせい」（NumberRejected）と「回線のせい・分からない」を
    アプリの言い分で分け、どの番号も受け付けない回線（アプリの設定の誤り）では行がすべて終わり、1つの番号だけが続けてかけられない
    ときは回線が止まり続けた（見直し18a の問題2・3）。"""


class CallWithheld(Exception):
    """かけようとしなかった（PC の上で緊急停止が押されている・PC の部品がつながっていない・前の頼みを待つうちに答えの期限を過ぎた）。
    番号も回線も試していないので、どの数にも入れない（試行は取り消し）。"""


class Phone(Protocol):
    def in_call(self) -> bool:
        """スマホが、いま通話の途中か（呼び出し中を含む）。分からなければ True（かけない側）。"""
        ...

    def start_call(self, phone_e164: str, voice_type: str | None = None) -> None:
        """かける。voice_type＝この通話で話す声の型（門が決めたもの）。通話の途中でおわびの録音を流すとき
        （`play_apology_and_hang_up`）は、この声の型の録音を流す（AI の声と違う声にしない。2026-10-22 の見直し14）。"""
        ...

    def hang_up(self) -> None: ...

    def play_apology_and_hang_up(self) -> None:
        """あらかじめ持っている、おわびの録音を流して切る（お客様を無言で放置しない）。サーバーとのつながりが通話の途中で切れたとき・
        サーバーの側の誤りで頼まれたとき。通話中でなければ、何もしない。録音は、いまの通話の声の型（`start_call` で受け取った）のもの。
        **流し方（2026-10-22 ユーザー決定）**：(1) 録音「恐れ入ります。こちらの通信に不具合が起きたようですので、改めてお電話させて
        いただいてもよろしいでしょうか？」を流す (2) お客様の返事（『はい』）を待つ（AI はいないので中身は聞き分けない。お客様が話し
        終わるか、決まった秒数で次へ）(3) 録音「大変申し訳ございません。それではいったんお電話を失礼いたします。」を流す (4) 切る。
        どちらの録音もシステムの録音（どの業務でも同じ。声の型ごとに CL-1 が作る）。かけ直しは、サーバーが途中で切れた通話として
        お詫びから始める（core/next_action）。"""
        ...

    def on_audio(self, send: Callable[[bytes], None]) -> None:
        """お客様の声をサーバーへ送る口を受け取る（形は会話＝CL-1 と電話接続の担当が決める。どの流れから呼んでもよい）。"""
        ...

    def on_event(self, send: Callable[[dict[str, Any]], None]) -> None:
        """電話の出来事（呼び出し・応答・切れた など。中身は会話＝CL-1 と電話接続の担当が決める）をサーバーへ送る口を受け取る
        （どの流れから呼んでもよい）。"""
        ...

